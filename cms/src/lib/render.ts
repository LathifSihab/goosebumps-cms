  marquee(): string {
    const items = this.site.marquee.items;
    // the track is duplicated so the CSS loop (translateX -50%) is seamless
    const one = items.map((it) => `    ${this.el('span', `mq.${it.id}`, it.text, 'class="mitem"').replace('</span>', ' <span class="mdot"></span></span>')}`).join('\n');
    return `
<!-- MARQUEE -->
<div class="mwrap">
  <div class="mtrack">
${one}
${one.replace(/ data-i18n="[^"]*"/g, ' aria-hidden="true"$&')}
  </div>
</div>
`;
  }

