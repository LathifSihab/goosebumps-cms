  /* ── nav / hero / marquee ── */

  navItems(visible: Section[]): string[] {
    return visible
      .filter((x) => x.nav.show && x.type !== 'contact')
      .map((x) => `<li><a href="#${esc(x.id)}" ${this.t(`nav.${x.id}`, x.nav.label).attr}>${rich(x.nav.label.en)}</a></li>`);
  }

  nav(visible: Section[]): string {
    const contact = visible.find((x) => x.type === 'contact');
    const cta = contact ? `\n    <li><a href="#${esc(contact.id)}" class="nav-cta" ${this.t('nav.cta', this.site.navCta).attr}>${rich(this.site.navCta.en)}</a></li>` : '';
    return `
<!-- NAV -->
<nav id="nav">
  <img class="nav-logo" id="nlogo" src="${this.url(this.site.brand.logo)}" alt="Goosebumps">
  <ul class="nav-menu" id="nav-menu">
    ${this.navItems(visible).join('\n    ')}${cta}
  </ul>
  <button class="nav-toggle" id="nav-toggle" type="button" aria-label="Menu" aria-controls="nav-menu" aria-expanded="false"><span></span><span></span><span></span></button>
</nav>
`;
  }

